#!/usr/bin/env python3
"""Compile declarative base definitions. Never extract rules from Dart source.

The generated constants remain the legacy executor's tables. This does not
implement the future era effects or dynamic building extensions.
"""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'content/catalog.json'
TARGET = ROOT / 'lib/content/catalog_generated.dart'


def literal(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False).replace('$', r'\$')
    if isinstance(value, list):
        return '[' + ', '.join(map(literal, value)) + ']'
    if isinstance(value, dict):
        return '{' + ', '.join(literal(k) + ': ' + literal(v)
                               for k, v in value.items()) + '}'
    if isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value):
        return str(value)
    raise ValueError('Unsupported catalog value')


def compile_catalog(raw):
    if set(raw) != {'schemaVersion', 'buildings', 'technologies'} or raw['schemaVersion'] != 1:
        raise ValueError('Unsupported catalog schema')
    tech_ids = {t['id'] for t in raw['technologies']}
    if len(tech_ids) != len(raw['technologies']):
        raise ValueError('Duplicate technologies')
    building_ids = set()
    text = ["// Generated by tool/generate_catalog.py from content/catalog.json.",
            "// Edit the declarative source; run the generator and its --check mode.",
            "import 'definitions.dart';", "", 'const buildings = <BuildingDefinition>[']
    for b in raw['buildings']:
        if b['id'] in building_ids or not isinstance(b['days'], int) or b['days'] < 1:
            raise ValueError('Invalid building identity or duration')
        building_ids.add(b['id'])
        if len(b['requires']) > 1 or not all(t in tech_ids for t in b['requires']):
            raise ValueError('Unsupported building prerequisite')
        for values in [b['costs'], b['dailyYield']]:
            if any(not isinstance(v, (int, float)) or isinstance(v, bool) or
                   not math.isfinite(v) or v < 0 for v in values.values()):
                raise ValueError('Invalid material quantity')
        args = [b['id'], b['name'], b['description'], b['costs'], b['dailyYield'], b['days']]
        if b['requires']:
            args.append(b['requires'][0])
        text.append('  BuildingDefinition(' + ', '.join(map(literal, args)) + '),')
    text += ['];', '', 'const technologies = <Technology>[']
    for t in raw['technologies']:
        if not all(dep in tech_ids for dep in t['requires']):
            raise ValueError('Missing technology prerequisite')
        args = [t['id'], t['name'], t['requires'], t['knowledgeCost'], t['description']]
        text.append('  Technology(' + ', '.join(map(literal, args)) + '),')
    text += ['];', '']
    return '\n'.join(text)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = compile_catalog(json.loads(SOURCE.read_text()))
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != generated:
            raise SystemExit('Generated catalog differs: run python3 tool/generate_catalog.py')
        print('Declarative catalog and generated executor definitions agree')
    else:
        TARGET.write_text(generated)
        print(TARGET.relative_to(ROOT))
